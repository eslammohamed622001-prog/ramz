def تحويل_لمعرف(نص):
    """تحويل النص إلى معرف صالح لـ JavaScript (بدون مسافات)"""
    return نص.replace(' ', '_').replace('-', '_')

def توليد_أمر(أمر, بادئة='        '):
    if أمر['النوع'] == 'طباعة':
        return f'{بادئة}alert(`{re.sub(r"\{([أ-يa-zA-Z_][أ-يa-zA-Z0-9_]*)\}", r"${\1}", أمر["النص"])}`);'
    elif أمر['النوع'] == 'متغير':
        if أمر.get('نوع_خاص') == 'حقل':
            # تحويل القيمة إلى رقم إذا كانت عملية حسابية
            return f'{بادئة}let {أمر["الاسم"]} = {أمر["القيمة"]};'
        elif أمر.get('نوع_خاص') == 'استرجاع':
            return f'{بادئة}let {أمر["الاسم"]} = {أمر["القيمة"]};'
        return f'{بادئة}let {أمر["الاسم"]} = {أمر["القيمة"]};'
    elif أمر['النوع'] == 'حفظ':
        return f'{بادئة}localStorage.setItem("{أمر["مفتاح"]}", document.getElementById("{أمر["مصدر"]}").value);'
    elif أمر['النوع'] == 'مسح':
        return f'{بادئة}localStorage.removeItem("{أمر["مفتاح"]}");'
    elif أمر['النوع'] == 'استدعاء_دالة':
        وسائط = ', '.join(أمر['الوسائط'])
        return f'{بادئة}{أمر["الاسم"]}({وسائط});'
    elif أمر['النوع'] == 'شرط':
        lines = [f'{بادئة}if ({أمر["الشرط"]}) {{']
        for sub in أمر['أوامر_إذا']: lines.append(توليد_أمر(sub, بادئة + '    '))
        lines.append(f'{بادئة}}}')
        if أمر['يوجد_وإلا']:
            lines.append(f'{بادئة}else {{')
            for sub in أمر['أوامر_وإلا']: lines.append(توليد_أمر(sub, بادئة + '    '))
            lines.append(f'{بادئة}}}')
        return '\n'.join(lines)
    elif أمر['النوع'] == 'حلقة':
        lines = [f'{بادئة}for (let i = 0; i < {أمر["العدد"]}; i++) {{']
        for sub in أمر['الأوامر']: lines.append(توليد_أمر(sub, بادئة + '    '))
        lines.append(f'{بادئة}}}')
        return '\n'.join(lines)
    elif أمر['النوع'] == 'محاولة':
        lines = [f'{بادئة}try {{']
        for sub in أمر['أوامر_المحاولة']: lines.append(توليد_أمر(sub, بادئة + '    '))
        lines.append(f'{بادئة}}}')
        if أمر['يوجد_امساك']:
            lines.append(f'{بادئة}catch ({أمر["اسم_الخطأ"]}) {{')
            for sub in أمر['أوامر_الامساك']: lines.append(توليد_أمر(sub, بادئة + '    '))
            lines.append(f'{بادئة}}}')
        return '\n'.join(lines)
    return ''

def توليد_الكود(شجرة):
    html = ['<!DOCTYPE html>', '<html lang="ar" dir="rtl">', '<head>', '<meta charset="UTF-8">', '<title>رَمْز</title>', '<style>',
            'body { font-family: "Cairo", Arial, sans-serif; background: #0B0C10; color: #C5C6C7; display: flex; justify-content: center; align-items: center; min-height: 100vh; margin: 0; }',
            '.container { text-align: center; padding: 40px; }', 'h1 { color: #D4AF37; }', 'p { color: #C5C6C7; }',
            'input { padding: 12px; border-radius: 8px; border: 2px solid #D4AF37; background: #1A1C23; color: white; margin: 10px; width: 250px; }',
            'button { padding: 12px 30px; margin: 10px; background: #D4AF37; color: #0B0C10; border: none; border-radius: 12px; cursor: pointer; }',
            '.card { background: #1A1C23; padding: 20px; border-radius: 16px; margin: 10px; display: inline-block; width: 200px; }',
            'img, video { max-width: 100%; border-radius: 12px; margin: 10px 0; }', 'ul { list-style: none; padding: 0; }', 'li { background: #1A1C23; margin: 5px 0; padding: 10px; border-radius: 8px; }',
            '</style></head><body>']
    
    if شجرة.get('شكل'):
        for صفحة in شجرة['شكل'].get('الصفحات', []):
            html.append(f'<div class="container" id="page-{تحويل_لمعرف(صفحة["الاسم"])}" style="display: block;">')
            for عنصر in صفحة.get('المحتوى', []):
                if عنصر['النوع'] in ('عنوان', 'زر', 'نص'):
                    tag = 'h1' if عنصر['النوع'] == 'عنوان' else ('button' if عنصر['النوع'] == 'زر' else 'p')
                    id_attr = f' id="btn-{تحويل_لمعرف(عنصر["النص"])}"' if عنصر['النوع'] == 'زر' else ''
                    html.append(f'<{tag}{id_attr}>{عنصر["النص"]}</{tag}>')
                elif عنصر['النوع'] == 'إدخال':
                    html.append(f'<input type="text" id="{عنصر["المعرف"]}" placeholder="{عنصر["النص_البديل"]}">')
                elif عنصر['النوع'] in ('صورة', 'فيديو'):
                    tag = 'img' if عنصر['النوع'] == 'صورة' else 'video controls'
                    html.append(f'<{tag} src="{عنصر["الرابط"]}"></{tag}>')
                elif عنصر['النوع'] == 'قائمة':
                    html.append(f'<ul id="list-{تحويل_لمعرف(عنصر["الاسم"])}">')
                    for item in عنصر['العناصر']: html.append(f'<li>{item["النص"]}</li>')
                    html.append('</ul>')
                elif عنصر['النوع'] == 'بطاقات':
                    for بطاقة in عنصر['البطاقات']:
                        html.append(f'<div class="card"><h3>{بطاقة["العنوان"]}</h3>')
                        for محتوى in بطاقة['المحتوى']:
                            tag = 'p' if محتوى['النوع'] == 'نص' else 'button'
                            id_attr = f' id="btn-{تحويل_لمعرف(محتوى["النص"])}"' if محتوى['النوع'] == 'زر' else ''
                            html.append(f'<{tag}{id_attr}>{محتوى["النص"]}</{tag}>')
                        html.append('</div>')
            html.append('</div>')

    if شجرة.get('معنى'):
        html.append('<script>')
        for بيان in شجرة['معنى'].get('البيانات', []):
            if بيان and بيان['النوع'] == 'دالة':
                html.append(f'function {بيان["الاسم"]}({", ".join(بيان["المعلمات"])}) {{')
                for أمر in بيان['الأوامر']: 
                    if أمر: html.append(توليد_أمر(أمر, '    '))
                html.append('}')
        
        for بيان in شجرة['معنى'].get('البيانات', []):
            if بيان and بيان['النوع'] == 'حدث' and بيان['الحدث'] == 'نقر':
                معرف_الزر = تحويل_لمعرف(بيان["الهدف"])
                html.append(f'document.getElementById("btn-{معرف_الزر}").addEventListener("click", function() {{')
                for أمر in بيان['الأوامر']: 
                    if أمر: html.append(توليد_أمر(أمر, '    '))
                html.append('});')
        html.append('</script>')
    
    html.append('</body></html>')
    return '\n'.join(html)

