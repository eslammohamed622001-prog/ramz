# 3. المُولّد (Code Generator)
# ==========================================
def توليد_أمر(أمر):
    """دالة مساعدة لتوليد كود JS لأي أمر"""
    if أمر['النوع'] == 'طباعة':
        نص_جافاسكريبت = re.sub(r'\{([أ-يa-zA-Z_][أ-يa-zA-Z0-9_]*)\}', r'${\1}', أمر['النص'])
        return f'            alert(`{نص_جافاسكريبت}`);'
    elif أمر['النوع'] == 'شرط':
        lines = []
        lines.append(f'            if ({أمر["الشرط"]}) {{')
        for sub_أمر in أمر['أوامر_إذا']:
            lines.append(توليد_أمر(sub_أمر)) # تم تصحيح الاسم هنا
        lines.append('            }')
        if أمر['يوجد_وإلا']:
            lines.append('            else {')
            for sub_أمر in أمر['أوامر_وإلا']:
                lines.append(توليد_أمر(sub_أمر)) # وتم تصحيح الاسم هنا أيضاً
            lines.append('            }')
        return '\n'.join(lines)
    return ''

def توليد_الكود(شجرة):
    html = []
    html.append('<!DOCTYPE html>')
    html.append('<html lang="ar" dir="rtl">')
    html.append('<head>')
    html.append('    <meta charset="UTF-8">')
    html.append('    <meta name="viewport" content="width=device-width, initial-scale=1.0">')
    html.append('    <title>رَمْز - مشروع تجريبي</title>')
    html.append('    <style>')
    html.append('        body { font-family: "Cairo", "Tajawal", sans-serif; background: #0B0C10; color: #C5C6C7; display: flex; justify-content: center; align-items: center; min-height: 100vh; margin: 0; }')
    html.append('        .container { text-align: center; padding: 40px; }')
    
    خريطة_الخصائص = {
        "اللون": "color", "الخلفية": "background-color", "الحجم": "font-size",
        "المحاذاة": "text-align", "الحواف": "border-radius", "العرض": "width", "الارتفاع": "height"
    }
    
    if شجرة.get('طراز'):
        for قاعدة in شجرة['طراز'].get('القواعد', []):
            الهدف = قاعدة['الهدف']
            محدد_العنصر = f"h1" if الهدف == "عنوان" else f"button"
            html.append(f'        {محدد_العنصر} {{')
            for اسم_عربي, قيمة in قاعدة['الخصائص'].items():
                اسم_انجليزي = خريطة_الخصائص.get(اسم_عربي, اسم_عربي)
                if اسم_عربي == "المحاذاة" and قيمة == "وسط":
                    قيمة = "center"
                html.append(f'            {اسم_انجليزي}: {قيمة};')
            html.append('        }')
            
    html.append('    </style>')
    html.append('</head>')
    html.append('<body>')
    
    if شجرة.get('شكل'):
        for صفحة in شجرة['شكل'].get('المحتوى', []):
            html.append(f'    <div class="container" id="page-{صفحة["الاسم"]}">')
            for عنصر in صفحة.get('المحتوى', []):
                if عنصر['النوع'] == 'عنوان':
                    html.append(f'        <h1>{عنصر["النص"]}</h1>')
                elif عنصر['النوع'] == 'زر':
                    html.append(f'        <button id="btn-{عنصر["النص"]}">{عنصر["النص"]}</button>')
            html.append('    </div>')
    
    if شجرة.get('معنى'):
        html.append('    <script>')
        for بيان in شجرة['معنى'].get('البيانات', []):
            if بيان['النوع'] == 'متغير':
                html.append(f'        let {بيان["الاسم"]} = {بيان["القيمة"]};')
        
        for بيان in شجرة['معنى'].get('البيانات', []):
            if بيان['النوع'] == 'حدث' and بيان['الحدث'] == 'نقر':
                html.append(f'        document.getElementById("btn-{بيان["الهدف"]}").addEventListener("click", function() {{')
                for أمر in بيان['الأوامر']:
                    html.append(توليد_أمر(أمر))
                html.append('        });')
        html.append('    </script>')
    
    html.append('</body>')
    html.append('</html>')
    return '\n'.join(html)

