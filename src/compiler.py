def بناء_الرموز(الكود):
    القواعد = [
        ('كلمة_مفتاحية', r'\b(شكل|صفحة|عنوان|زر|معنى|عند|النقر|على|أظهر|طراز|تنسيق|خاصية|إدخال|حقل|ليكن|إذا|وإلا|كرر|مرات|دالة|احفظ|من|استرجع|امسح|حاول|امسك|بطاقات|بطاقة|قائمة|عنصر|صورة|فيديو|انتقل|إلى|نص)\b'),
        ('نص_مقتبس', r'"[^"]*"'),
        ('رقم', r'\d+(\.\d+)?'),
        ('قوس_فتح', r'\{'),
        ('قوس_إغلاق', r'\}'),
        ('قوس_دائري_فتح', r'\('),
        ('قوس_دائري_إغلاق', r'\)'),
        ('فاصلة', r','),
        ('عامل', r'='),
        ('عامل_مقارنة', r'==|!=|>=|<=|>|<'),
        ('عامل_حسابي', r'[\+\-\*\/]'),
        ('تعليق', r'//.*'),
        ('معرّف', r'[أ-يa-zA-Z_][أ-يa-zA-Z0-9_]*'),
        ('مسافة', r'\s+'),
    ]
    نمط_موحد = '|'.join(f'(?P<{اسم}>{قاعدة})' for اسم, قاعدة in القواعد)
    الرموز = []
    for مطابقة in re.finditer(نمط_موحد, الكود):
        نوع = مطابقة.lastgroup
        قيمة = مطابقة.group()
        if نوع and نوع not in ('مسافة', 'تعليق'):
            الرموز.append({'النوع': نوع, 'القيمة': قيمة})
    return الرموز

class محلل_نحوي:
    def __init__(self, الرموز):
        self.الرموز = الرموز
        self.الموضع = 0

    def استهلك(self, النوع_المتوقع, رسالة_خطأ):
        if self.الموضع < len(self.الرموز):
            رمز = self.الرموز[self.الموضع]
            if رمز['النوع'] == النوع_المتوقع or رمز['القيمة'] == النوع_المتوقع:
                self.الموضع += 1
                return رمز
            raise Exception(f"خطأ: {رسالة_خطأ}. وجدنا: {رمز['القيمة']}")
        raise Exception(f"خطأ: {رسالة_خطأ}")

    def تحليل(self):
        شجرة = {'شكل': None, 'طراز': None, 'معنى': None}
        while self.الموضع < len(self.الرموز):
            رمز = self.الرموز[self.الموضع]
            if رمز['القيمة'] == 'شكل': شجرة['شكل'] = self.تحليل_شكل()
            elif رمز['القيمة'] == 'طراز': شجرة['طراز'] = self.تحليل_طراز()
            elif رمز['القيمة'] == 'معنى': شجرة['معنى'] = self.تحليل_معنى()
            else: self.الموضع += 1
        return شجرة

    def تحليل_شكل(self):
        self.استهلك('شكل', "توقع شكل"); self.استهلك('قوس_فتح', "توقع {")
        عقدة = {'النوع': 'شكل', 'الصفحات': []}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            عقدة['الصفحات'].append(self.تحليل_صفحة())
        self.استهلك('قوس_إغلاق', "توقع }"); return عقدة

