            رمز_حالي = self.الرموز[self.الموضع]
            if رمز_حالي['النوع'] == 'كلمة_مفتاحية' and رمز_حالي['القيمة'] in ('ليكن', 'عند', 'أظهر', 'إذا', 'كرر', 'دالة', 'احفظ', 'امسح', 'حاول'): break
            if رمز_حالي['النوع'] == 'قوس_إغلاق': break
