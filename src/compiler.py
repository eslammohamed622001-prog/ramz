import re
import os
import argparse
import sys

def بناء_الرموز(الكود):
    القواعد = [
        ('كلمة_مفتاحية', r'\b(شكل|صفحة|عنوان|زر|معنى|عند|النقر|على|أظهر|طراز|تنسيق|خاصية|إدخال|حقل|ليكن|إذا|وإلا)\b'),
        ('نص_مقتبس', r'"[^"]*"'),
        ('رقم', r'\d+(\.\d+)?'),
        ('قوس_فتح', r'\{'),
        ('قوس_إغلاق', r'\}'),
        ('عامل', r'='),
        ('عامل_مقارنة', r'==|!=|>=|<=|>|<'),
        ('عامل_حسابي', r'[\+\-\*\/]'),
        ('معرّف', r'[أ-يa-zA-Z_][أ-يa-zA-Z0-9_]*'),
        ('مسافة', r'\s+'),
    ]
    نمط_موحد = '|'.join(f'(?P<{اسم}>{قاعدة})' for اسم, قاعدة in القواعد)
    الرموز = []
    for مطابقة in re.finditer(نمط_موحد, الكود):
        نوع = مطابقة.lastgroup
        قيمة = مطابقة.group()
        if نوع and نوع not in ('مسافة',):
            الرموز.append({'النوع': نوع, 'القيمة': قيمة})
    return الرموز

class محلل_نحوي:
    def __init__(self, الرموز):
        self.الرموز = الرموز
        self.الموضع = 0

    def استهلك(self, النوع_المتوقع, رسالة_خطأ):
        if self.الموضع < len(self.الرموز):
            رمز = self.الرموز[self.الموضع]
            if رمز['النوع'] == النوع_المتوقع or رمز['القيمة'] == النوع_المتوقع:
                self.الموضع += 1
                return رمز
            raise Exception(f"خطأ: {رسالة_خطأ}. وجدنا: {رمز['القيمة']}")
        raise Exception(f"خطأ: {رسالة_خطأ}")

    def تحليل(self):
        شجرة = {'شكل': None, 'طراز': None, 'معنى': None}
        while self.الموضع < len(self.الرموز):
            رمز = self.الرموز[self.الموضع]
            if رمز['القيمة'] == 'شكل': شجرة['شكل'] = self.تحليل_شكل()
            elif رمز['القيمة'] == 'طراز': شجرة['طراز'] = self.تحليل_طراز()
            elif رمز['القيمة'] == 'معنى': شجرة['معنى'] = self.تحليل_معنى()
            else: self.الموضع += 1
        return شجرة

    def تحليل_شكل(self):
        self.استهلك('شكل', "توقع شكل"); self.استهلك('قوس_فتح', "توقع {")
        عقدة = {'النوع': 'شكل', 'الصفحات': []}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            عقدة['الصفحات'].append(self.تحليل_صفحة())
        self.استهلك('قوس_إغلاق', "توقع }"); return عقدة

    def تحليل_صفحة(self):
        self.استهلك('صفحة', "توقع صفحة"); اسم_الصفحة = self.استهلك('نص_مقتبس', "توقع اسم")['القيمة'].strip('"')
        self.استهلك('قوس_فتح', "توقع {"); عقدة = {'النوع': 'صفحة', 'الاسم': اسم_الصفحة, 'المحتوى': []}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            رمز = self.الرموز[self.الموضع]
            if رمز['القيمة'] in ('عنوان', 'زر'): عقدة['المحتوى'].append(self.تحليل_عنصر(رمز['القيمة']))
            elif رمز['القيمة'] == 'إدخال': عقدة['المحتوى'].append(self.تحليل_إدخال())
            else: self.الموضع += 1
        self.استهلك('قوس_إغلاق', "توقع }"); return عقدة

    def تحليل_عنصر(self, نوع_العنصر):
        self.استهلك(نوع_العنصر, f"توقع {نوع_العنصر}"); رمز = self.استهلك('نص_مقتبس', "توقع نص")
        return {'النوع': نوع_العنصر, 'النص': رمز['القيمة'].strip('"')}

    def تحليل_إدخال(self):
        self.استهلك('إدخال', "توقع إدخال"); المعرف = self.استهلك('نص_مقتبس', "توقع المعرف")['القيمة'].strip('"')
        النص_البديل = self.استهلك('نص_مقتبس', "توقع النص")['القيمة'].strip('"')
        return {'النوع': 'إدخال', 'المعرف': المعرف, 'النص_البديل': النص_البديل}

    def تحليل_طراز(self):
        self.استهلك('طراز', "توقع طراز"); self.استهلك('قوس_فتح', "توقع {"); عقدة = {'النوع': 'طراز', 'القواعد': []}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            عقدة['القواعد'].append(self.تحليل_تنسيق())
        self.استهلك('قوس_إغلاق', "توقع }"); return عقدة

    def تحليل_تنسيق(self):
        self.استهلك('تنسيق', "توقع تنسيق"); الهدف = self.استهلك('نص_مقتبس', "توقع الهدف")['القيمة'].strip('"')
        self.استهلك('قوس_فتح', "توقع {"); خصائص = {}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            self.استهلك('خاصية', "توقع خاصية"); اسم_الخاصية = self.استهلك('نص_مقتبس', "توقع الاسم")['القيمة'].strip('"')
            self.استهلك('عامل', "توقع ="); قيمة_الخاصية = self.استهلك('نص_مقتبس', "توقع القيمة")['القيمة'].strip('"')
            خصائص[اسم_الخاصية] = قيمة_الخاصية
        self.استهلك('قوس_إغلاق', "توقع }"); return {'الهدف': الهدف, 'الخصائص': خصائص}

    def تحليل_معنى(self):
        self.استهلك('معنى', "توقع معنى"); self.استهلك('قوس_فتح', "توقع {"); عقدة = {'النوع': 'معنى', 'البيانات': []}
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            عقدة['البيانات'].append(self.تحليل_بيان())
        self.استهلك('قوس_إغلاق', "توقع }"); return عقدة

    def تحليل_بيان(self):
        رمز = self.الرموز[self.الموضع]
        if رمز['القيمة'] == 'عند': return self.تحليل_حدث()
        elif رمز['القيمة'] == 'أظهر': return self.تحليل_طباعة()
        elif رمز['القيمة'] == 'ليكن': return self.تحليل_متغير()
        elif رمز['القيمة'] == 'إذا': return self.تحليل_شرط()
        else: self.الموضع += 1; return None

    def تحليل_متغير(self):
        self.استهلك('ليكن', "توقع ليكن"); اسم_المتغير = self.استهلك('معرّف', "توقع اسم")['القيمة']
        self.استهلك('عامل', "توقع =")
        if self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['القيمة'] == 'حقل':
            self.استهلك('حقل', "توقع حقل"); معرف_الحقل = self.استهلك('نص_مقتبس', "توقع المعرف")['القيمة'].strip('"')
            return {'النوع': 'متغير', 'الاسم': اسم_المتغير, 'القيمة': f'parseFloat(document.getElementById("{معرف_الحقل}").value) || 0', 'نوع_خاص': 'حقل'}
        
        قيمة = []
        while self.الموضع < len(self.الرموز):
            رمز_حالي = self.الرموز[self.الموضع]
            if رمز_حالي['النوع'] == 'كلمة_مفتاحية' and رمز_حالي['القيمة'] in ('ليكن', 'عند', 'أظهر', 'إذا'): break
            if رمز_حالي['النوع'] == 'قوس_إغلاق': break
            قيمة.append(رمز_حالي['القيمة']); self.الموضع += 1
        return {'النوع': 'متغير', 'الاسم': اسم_المتغير, 'القيمة': " ".join(قيمة).strip()}

    def تحليل_شرط(self):
        self.استهلك('إذا', "توقع إذا"); شرط_tokens = []
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_فتح':
            شرط_tokens.append(self.الرموز[self.الموضع]['القيمة']); self.الموضع += 1
        self.استهلك('قوس_فتح', "توقع {"); أوامر_إذا = []
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            أمر = self.تحليل_بيان()
            if أمر: أوامر_إذا.append(أمر)
        self.استهلك('قوس_إغلاق', "توقع }"); أوامر_وإلا = []; يوجد_وإلا = False
        if self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['القيمة'] == 'وإلا':
            يوجد_وإلا = True; self.استهلك('وإلا', "توقع وإلا"); self.استهلك('قوس_فتح', "توقع {")
            while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
                أمر = self.تحليل_بيان()
                if أمر: أوامر_وإلا.append(أمر)
            self.استهلك('قوس_إغلاق', "توقع }")
        return {'النوع': 'شرط', 'الشرط': " ".join(شرط_tokens), 'أوامر_إذا': أوامر_إذا, 'أوامر_وإلا': أوامر_وإلا, 'يوجد_وإلا': يوجد_وإلا}

    def تحليل_حدث(self):
        self.استهلك('عند', "توقع عند"); self.استهلك('النقر', "توقع النقر"); self.استهلك('على', "توقع على")
        اسم_الزر = self.استهلك('نص_مقتبس', "توقع اسم الزر")['القيمة'].strip('"'); self.استهلك('قوس_فتح', "توقع {"); الأوامر = []
        while self.الموضع < len(self.الرموز) and self.الرموز[self.الموضع]['النوع'] != 'قوس_إغلاق':
            أمر = self.تحليل_بيان()
            if أمر: الأوامر.append(أمر)
        self.استهلك('قوس_إغلاق', "توقع }"); return {'النوع': 'حدث', 'الحدث': 'نقر', 'الهدف': اسم_الزر, 'الأوامر': الأوامر}

    def تحليل_طباعة(self):
        self.استهلك('أظهر', "توقع أظهر"); النص = self.استهلك('نص_مقتبس', "توقع نص")['القيمة'].strip('"')
        return {'النوع': 'طباعة', 'النص': النص}

def تحويل_لمعرف(نص):
    return نص.replace(' ', '_').replace('-', '_')

def توليد_أمر(أمر, بادئة='        '):
    if أمر['النوع'] == 'طباعة':
        return f'{بادئة}alert(`{re.sub(r"\{([أ-يa-zA-Z_][أ-يa-zA-Z0-9_]*)\}", r"${\1}", أمر["النص"])}`);'
    elif أمر['النوع'] == 'متغير':
        return f'{بادئة}let {أمر["الاسم"]} = {أمر["القيمة"]};'
    elif أمر['النوع'] == 'شرط':
        lines = [f'{بادئة}if ({أمر["الشرط"]}) {{']
        for sub in أمر['أوامر_إذا']: lines.append(توليد_أمر(sub, بادئة + '    '))
        lines.append(f'{بادئة}}}')
        if أمر['يوجد_وإلا']:
            lines.append(f'{بادئة}else {{')
            for sub in أمر['أوامر_وإلا']: lines.append(توليد_أمر(sub, بادئة + '    '))
            lines.append(f'{بادئة}}}')
        return '\n'.join(lines)
    return ''

def توليد_الكود(شجرة):
    html = ['<!DOCTYPE html>', '<html lang="ar" dir="rtl">', '<head>', '<meta charset="UTF-8">', '<title>رَمْز</title>', '<style>',
            'body { font-family: Arial; background: #0B0C10; color: #C5C6C7; display: flex; justify-content: center; align-items: center; min-height: 100vh; margin: 0; }',
            '.container { text-align: center; padding: 40px; }', 'h1 { color: #D4AF37; }',
            'input { padding: 12px; border-radius: 8px; border: 2px solid #D4AF37; background: #1A1C23; color: white; margin: 10px; width: 250px; }',
            'button { padding: 12px 30px; margin: 10px; background: #D4AF37; color: #0B0C10; border: none; border-radius: 12px; cursor: pointer; }',
            '</style></head><body>']
    
    if شجرة.get('شكل'):
        for صفحة in شجرة['شكل'].get('الصفحات', []):
            html.append('<div class="container">')
            for عنصر in صفحة.get('المحتوى', []):
                if عنصر['النوع'] == 'عنوان':
                    html.append(f'<h1>{عنصر["النص"]}</h1>')
                elif عنصر['النوع'] == 'زر':
                    html.append(f'<button id="btn-{تحويل_لمعرف(عنصر["النص"])}">{عنصر["النص"]}</button>')
                elif عنصر['النوع'] == 'إدخال':
                    html.append(f'<input type="text" id="{عنصر["المعرف"]}" placeholder="{عنصر["النص_البديل"]}">')
            html.append('</div>')
    
    if شجرة.get('معنى'):
        html.append('<script>')
        for بيان in شجرة['معنى'].get('البيانات', []):
            if بيان and بيان['النوع'] == 'حدث' and بيان['الحدث'] == 'نقر':
                معرف_الزر = تحويل_لمعرف(بيان["الهدف"])
                html.append(f'document.getElementById("btn-{معرف_الزر}").addEventListener("click", function() {{')
                for أمر in بيان['الأوامر']: 
                    if أمر: html.append(توليد_أمر(أمر, '    '))
                html.append('});')
        html.append('</script>')
    
    html.append('</body></html>')
    return '\n'.join(html)

def رئيسي():
    محلل_الأوامر = argparse.ArgumentParser(description="مترجم رَمْز")
    محلل_الأوامر.add_argument('--version', action='version', version='رَمْز 2.0.0')
    الأوامر_الفرعية = محلل_الأوامر.add_subparsers(dest='الأمر')
    أمر_البناء = الأوامر_الفرعية.add_parser('build')
    أمر_البناء.add_argument('ملف_الإدخال', nargs='?', default='examples/test.ramz')
    أمر_البناء.add_argument('-o', '--مخرج', default='output/index.html')
    الوسائط = محلل_الأوامر.parse_args()

    if الوسائط.الأمر == 'build':
        if not os.path.exists(الوسائط.ملف_الإدخال):
            print("❌ الملف غير موجود"); sys.exit(1)
        with open(الوسائط.ملف_الإدخال, "r", encoding="utf-8") as ملف:
            كود_مصدري = ملف.read()
        try:
            الرموز = بناء_الرموز(كود_مصدري)
            الشجرة = محلل_نحوي(الرموز).تحليل()
            os.makedirs(os.path.dirname(الوسائط.مخرج), exist_ok=True)
            with open(الوسائط.مخرج, "w", encoding="utf-8") as ملف_المخرج:
                ملف_المخرج.write(توليد_الكود(الشجرة))
            print("🎉 تم البناء بنجاح! افتح output/index.html")
        except Exception as خطأ:
            print(f"❌ خطأ: {خطأ}")

if __name__ == "__main__":
    رئيسي()