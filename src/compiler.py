def رئيسي():
    محلل_الأوامر = argparse.ArgumentParser(
        description="مترجم لغة رَمْز - منظومة تطوير ويب عربية أصيلة",
        formatter_class=argparse.RawTextHelpFormatter
    )
    
    محلل_الأوامر.add_argument('--version', action='version', version='رَمْز الإصدار 1.2.0 (دعم الشروط إذا/وإلا)')
    
    الأوامر_الفرعية = محلل_الأوامر.add_subparsers(dest='الأمر', help='الأوامر المتاحة')
    
    أمر_البناء = الأوامر_الفرعية.add_parser('build', help='بناء المشروع وتوليد ملفات HTML/CSS/JS')
    أمر_البناء.add_argument('ملف_الإدخال', nargs='?', default='examples/test.ramz', help='مسار ملف رَمْز المراد بناؤه')
    أمر_البناء.add_argument('-o', '--مخرج', default='output/index.html', help='مسار ملف المخرج')

    الوسائط = محلل_الأوامر.parse_args()

    if الوسائط.الأمر == 'build':
        print(f"🚀 بدء بناء المشروع من: {الوسائط.ملف_الإدخال}")
        print("=" * 70)
        
        if not os.path.exists(الوسائط.ملف_الإدخال):
            print(f"❌ خطأ: لم يتم العثور على الملف '{الوسائط.ملف_الإدخال}'")
            sys.exit(1)
            
        with open(الوسائط.ملف_الإدخال, "r", encoding="utf-8") as ملف:
            كود_مصدري = ملف.read()
            
        try:
            الرموز = بناء_الرموز(كود_مصدري)
            المحلل = محلل_نحوي(الرموز)
            الشجرة = المحلل.تحليل()
            كود_المخرج = توليد_الكود(الشجرة)
            
            مجلد_المخرج = os.path.dirname(الوسائط.مخرج)
            if مجلد_المخرج:
                os.makedirs(مجلد_المخرج, exist_ok=True)
                
            with open(الوسائط.مخرج, "w", encoding="utf-8") as ملف_المخرج:
                ملف_المخرج.write(كود_المخرج)
            
            print("✅ [1/3] التحليل اللفظي والنحوي ... تم")
            print("✅ [2/3] توليد HTML + CSS + JS ... تم")
            print("✅ [3/3] حفظ الملف ... تم")
            print("-" * 70)
            print(f"🎉 تم بناء المشروع بنجاح!")
            print(f"📁 الملف الناتج: {الوسائط.مخرج}")
            print(f"🌐 افتح الملف في المتصفح، وانقر على الزر لترى السحر!")
            
        except Exception as خطأ:
            print(f"❌ خطأ أثناء البناء: {خطأ}")
            sys.exit(1)
            
    elif الوسائط.الأمر is None:
        محلل_الأوامر.print_help()
    else:
        print(f"❌ أمر غير معروف: {الوسائط.الأمر}")
        محلل_الأوامر.print_help()

if __name__ == "__main__":
    رئيسي()